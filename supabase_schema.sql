create table if not exists public.feedbacks (
  id bigint generated by default as identity primary key,
  usuario_id uuid references auth.users(id) on delete set null,
  perfil text not null check (perfil in ('Aluno','Professor','Funcionário')),
  serie text,
  idade text not null,
  entendeu boolean not null,
  comentario text,
  estrelas integer not null check (estrelas between 1 and 5),
  criado_em timestamptz not null default now()
);

alter table public.feedbacks enable row level security;

drop policy if exists "feedback_insert_auth" on public.feedbacks;
create policy "feedback_insert_auth"
on public.feedbacks for insert
to authenticated
with check (usuario_id = auth.uid());

drop policy if exists "feedback_select_auth" on public.feedbacks;
create policy "feedback_select_auth"
on public.feedbacks for select
to authenticated
using (true);

-- Função usada pela página Informativos para receber apenas os agregados.
-- Assim, o frontend não precisa expor comentários ou dados de usuários para gerar os gráficos.
create or replace function public.get_feedback_analytics()
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  total_count integer;
  sim_count integer;
  nao_count integer;
  avg_stars numeric;
  profile_json jsonb;
  stars_json jsonb;
begin
  select count(*) into total_count from public.feedbacks;
  select count(*) into sim_count from public.feedbacks where entendeu = true;
  select count(*) into nao_count from public.feedbacks where entendeu = false;
  select coalesce(round(avg(estrelas)::numeric, 2), 0) into avg_stars from public.feedbacks;

  select coalesce(
    jsonb_object_agg(perfil, quantidade),
    '{}'::jsonb
  )
  into profile_json
  from (
    select perfil, count(*)::int as quantidade
    from public.feedbacks
    group by perfil
    order by perfil
  ) p;

  select coalesce(
    jsonb_agg(quantidade order by estrela),
    '[0,0,0,0,0]'::jsonb
  )
  into stars_json
  from (
    select s.estrela, coalesce(f.quantidade, 0)::int as quantidade
    from generate_series(1,5) s(estrela)
    left join (
      select estrelas, count(*)::int as quantidade
      from public.feedbacks
      group by estrelas
    ) f on f.estrelas = s.estrela
  ) x;

  return jsonb_build_object(
    'total', total_count,
    'entendeu_sim', sim_count,
    'entendeu_nao', nao_count,
    'media_estrelas', avg_stars,
    'perfil', profile_json,
    'estrelas', stars_json
  );
end;
$$;

revoke all on function public.get_feedback_analytics() from public;
grant execute on function public.get_feedback_analytics() to anon, authenticated;
